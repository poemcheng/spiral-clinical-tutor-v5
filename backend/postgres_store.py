"""PostgreSQL implementation of the existing transactional Store contract.

Explicitly opt in with DATABASE_URL; local SQLite files are never migrated or
overwritten by startup. Use one application worker for per-session turn locks.
"""
import ast,contextlib,re,sqlite3,threading
from pathlib import Path
from .store import Store

ID_TABLES={'users','logins','attempts','sessions','messages','reviews','events'}
def translate(sql):
    sql=re.sub(r"json_extract\((\w+(?:\.\w+)?),'\$\.(\w+)'\)\s*=\s*\?",r"(\1::jsonb ->> '\2')=CAST(? AS text)",sql)
    sql=re.sub(r"json_extract\((\w+(?:\.\w+)?),'\$\.(\w+)'\)",r"(\1::jsonb ->> '\2')",sql)
    sql=sql.replace('MAX(approved_level,?)','GREATEST(approved_level,?)')
    ignored='INSERT OR IGNORE' in sql.upper()
    sql=re.sub('INSERT OR IGNORE','INSERT',sql,flags=re.I).replace('?','%s')
    if ignored:sql=sql.rstrip().rstrip(';')+' ON CONFLICT DO NOTHING'
    match=re.match(r'\s*INSERT INTO\s+(\w+)',sql,re.I)
    returns=bool(match and match.group(1) in ID_TABLES and 'RETURNING' not in sql.upper())
    if returns:sql+=' RETURNING id'
    return sql,returns

class Cursor:
    def __init__(self,cursor,lastrowid=None):self.cursor=cursor;self.lastrowid=lastrowid
    @staticmethod
    def row(row):
        if row and row.get('passed') in ('true','false','0','1'):row['passed']=row['passed'] in ('true','1')
        return row
    def fetchone(self):return self.row(self.cursor.fetchone())
    def fetchall(self):return [self.row(r) for r in self.cursor.fetchall()]

class Connection:
    def __init__(self,connection):self.raw=connection
    def execute(self,sql,args=()):
        import psycopg
        sql,returns=translate(sql)
        try:
            c=self.raw.execute(sql,args)
            value=c.fetchone()['id'] if returns else None
            return Cursor(c,value)
        except psycopg.IntegrityError as e:raise sqlite3.IntegrityError(str(e)) from e
    def commit(self):self.raw.commit()
    def rollback(self):self.raw.rollback()
    def close(self):self.raw.close()

class PostgresStore(Store):
    def __init__(self,url):
        import psycopg
        from psycopg.rows import dict_row
        self.path='postgresql';self.lock=threading.RLock();self.conn=Connection(psycopg.connect(url,row_factory=dict_row))
        # Reuse the immutable CREATE TABLE schema rather than maintaining two schemas.
        tree=ast.parse((Path(__file__).parent/'store.py').read_text(encoding='utf-8'))
        schema=next(n.args[0].value for n in ast.walk(tree) if isinstance(n,ast.Call) and isinstance(n.func,ast.Attribute) and n.func.attr=='executescript')
        schema=schema.replace('id INTEGER PRIMARY KEY','id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').replace(' REAL',' DOUBLE PRECISION')
        with self.tx() as c:
            for statement in schema.split(';'):
                if statement.strip():c.execute(statement)
            c.execute('INSERT OR IGNORE INTO schema_version VALUES (2)')
    def backup(self,destination):
        raise RuntimeError('PostgreSQL 請使用 pg_dump 備份；不會匯出成 SQLite。')

def open_store():
    import os
    url=os.getenv('DATABASE_URL','')
    return PostgresStore(url) if url else Store()
