"""Build a credential-free, standalone CATIA learning bundle for GitHub Pages."""
import argparse
import copy
import json
from pathlib import Path
import runpy

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / 'web_portal' / 'catia'


def build():
    curriculum = runpy.run_path(str(ROOT / 'backend/graphics_curriculum.py'))
    learning = json.loads((ROOT / 'data/graphics/catia_learning.json').read_text(encoding='utf-8-sig'))
    stages = []
    for task in curriculum['TASKS']:
        stage = copy.deepcopy(task)
        stage['step_titles'] = curriculum['STEPS']
        stage['quizzes'] = []
        for key, title in [('pre', '概念起點練習'), ('transfer', '新情境遷移練習')]:
            quiz = stage.pop(key)
            correct = quiz['options'][quiz['answer']]
            stage['quizzes'].append({'id': f"{task['id']}-{key}", **quiz,
                                    'explanation': f'{title}：{correct}。請再用自己的模型、數值與證據說明理由。'})
        stages.append(stage)
    stage_ids = {stage['id'] for stage in stages}
    lesson_ids, question_ids = set(), set()
    for lesson in learning['lessons']:
        if lesson['stage_id'] not in stage_ids or lesson['id'] in lesson_ids:
            raise ValueError('Unknown stage or duplicate lesson ID')
        lesson_ids.add(lesson['id'])
        for field in ('knowledge', 'steps', 'quiz', 'sources'):
            if not lesson.get(field):
                raise ValueError(f"Lesson {lesson['id']} has no {field}")
        for step in lesson['steps']:
            if not all(isinstance(step.get(field), str) and step[field].strip()
                       for field in ('title', 'action', 'checkpoint', 'evidence')):
                raise ValueError('Incomplete practical step')
    quizzes = [quiz for lesson in learning['lessons'] for quiz in lesson['quiz']]
    quizzes += [quiz for stage in stages for quiz in stage['quizzes']]
    for quiz in quizzes:
        if quiz['id'] in question_ids or type(quiz['answer']) is not int or not 0 <= quiz['answer'] < len(quiz['options']):
            raise ValueError('Duplicate quiz ID or invalid answer index')
        question_ids.add(quiz['id'])
    for stage in stages:
        for prompts in stage['prompts'].values():
            for prompt in prompts:
                if prompt['id'] in question_ids:
                    raise ValueError('Duplicate question ID')
                question_ids.add(prompt['id'])
    data = {**learning, 'curriculum_version': curriculum['VERSION'], 'stages': stages,
            'sources': curriculum['SOURCES'],
            'storage_notice': '進度儲存在此瀏覽器；匯出檔案可備份或交給老師。',
            'practice_notice': '本站為公開自學練習，題目與解說公開；練習結果不作為正式成績。'}
    serialized = json.dumps(data, ensure_ascii=False, indent=2).replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    script = '/* Generated by tools/build_catia_site.py; public teaching content only. */\nwindow.CATIA_LEARNING_DATA = ' + serialized + ';\n'
    worksheet = [learning['title'], '學生姓名／代號：________________',
                 '自學練習題本；依實際CATIA操作作答。進度與作答可由網站匯出備份。',
                 '公開網址：https://poemcheng.github.io/spiral-clinical-tutor-v5/catia/', '']
    for stage in stages:
        worksheet += [f"=== 第{stage['weeks']}週｜{stage['title']} ===", stage['brief'], '']
        for step in range(1, 7):
            worksheet += [f"步驟{step}｜{stage['step_titles'][step - 1]}"]
            for index, prompt in enumerate(stage['prompts'][str(step)], 1):
                worksheet += [f"{index}. {prompt['prompt']}", f"提示：{prompt['placeholder']}", '作答：', '', '']
        for quiz in stage['quizzes']:
            worksheet += [quiz['question']] + [f"{chr(65 + index)}. {option}" for index, option in enumerate(quiz['options'])] + ['我的選項與理由：', '']
    worksheet += ['=== 知識與操作課堂練習 ===']
    for lesson in learning['lessons']:
        worksheet += [lesson['title']]
        for quiz in lesson['quiz']:
            worksheet += [quiz['question']] + [f"{chr(65 + index)}. {option}" for index, option in enumerate(quiz['options'])] + ['我的選項與理由：', '']
    return {'learning-data.js': script, 'practice-worksheet.txt': '\n'.join(worksheet) + '\n'}, data


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='Check committed data without rewriting it')
    args = parser.parse_args()
    files, data = build()
    DESTINATION.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        destination = DESTINATION / name
        if args.check:
            if not destination.exists() or destination.read_text(encoding='utf8') != content:
                raise SystemExit(f'Generated file is stale: {name}')
        else:
            destination.write_text(content, encoding='utf8')
    print(json.dumps({'stages': len(data['stages']), 'lessons': len(data['lessons']),
                      'practical_steps': sum(len(lesson['steps']) for lesson in data['lessons']),
                      'open_questions': sum(len(prompts) for stage in data['stages'] for prompts in stage['prompts'].values()),
                      'practice_quizzes': sum(len(lesson['quiz']) for lesson in data['lessons']) + sum(len(stage['quizzes']) for stage in data['stages'])}))


if __name__ == '__main__':
    main()
