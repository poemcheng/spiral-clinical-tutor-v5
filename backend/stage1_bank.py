def role_items(profession, level):
    if profession not in ROLE_TASKS or level not in LEVEL_TASKS:
        raise ValueError('職種或 Level 不符題庫設定。')
    return [{
        'item_id': f'S1-{profession}-L{level}-{dim["id"]}-V{variant+1}',
        'dimension': dim['id'], 'dimension_name': dim['name'],
        'prompt': LEVEL_TASKS[level][variant].format(task=tasks[variant]),
        'role_task': tasks[variant], 'profession': profession, 'level': level,
        'adaptation_version': BANK_VERSION,
    } for dim, tasks in zip(DIMENSIONS, ROLE_TASKS[profession]) for variant in range(2)]


def profession_catalog(registry):
    return [{
        'profession': code, 'profession_label': value['label'], 'symptom': '肌少症',
        'assessment_available': True,
        'training_available': code in TRAINING_PROFESSIONS and bool(registry.cases_for('肌少症', code)),
        'case_count': len(registry.cases_for('肌少症', code)) if code in TRAINING_PROFESSIONS else 0,
        'content_status': '既有肌少症教案／跨專業案例' if code in TRAINING_PROFESSIONS else '階段一已開放；肌少症後續教案待建置',
        'assessment_status': '職種與 Level 分層自評草稿，待職類教師審核',
    } for code, value in PROFESSIONS.items()]
